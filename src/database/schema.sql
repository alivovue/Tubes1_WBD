-- Schakker website metadata only. Managed target databases remain separate.
-- Apply once to an empty database. All table/index creation is transactional.
BEGIN;
SET LOCAL search_path = pg_catalog, public;

CREATE TABLE public.users (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username            VARCHAR(100) NOT NULL,
    display_name        VARCHAR(150) NOT NULL,
    password_hash       TEXT NOT NULL,
    is_platform_admin   BOOLEAN NOT NULL DEFAULT FALSE,
    is_active           BOOLEAN NOT NULL DEFAULT TRUE,
    created_by          BIGINT REFERENCES public.users(id),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Preserve the supplied username spelling while enforcing uniqueness by case.
CREATE UNIQUE INDEX users_username_lower_key ON public.users (lower(username));

CREATE TABLE public.access_groups (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(100) NOT NULL UNIQUE,
    description     TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE public.user_groups (
    user_id     BIGINT NOT NULL REFERENCES public.users(id),
    group_id    BIGINT NOT NULL REFERENCES public.access_groups(id),
    joined_at   TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY (user_id, group_id)
);

CREATE INDEX user_groups_group_id_idx ON public.user_groups (group_id);

-- Connection metadata only; inserting a record does not create/connect a target.
CREATE TABLE public.managed_databases (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    display_name         VARCHAR(150) NOT NULL UNIQUE,
    dbms_type            VARCHAR(30) NOT NULL DEFAULT 'postgresql',
    host                 TEXT NOT NULL,
    port                 INTEGER NOT NULL DEFAULT 5432,
    database_name        TEXT NOT NULL,
    db_username          TEXT NOT NULL,
    encrypted_password   BYTEA NOT NULL,
    connection_options   JSONB DEFAULT '{}'::JSONB,
    is_active            BOOLEAN NOT NULL DEFAULT TRUE,
    created_by           BIGINT REFERENCES public.users(id),
    created_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT managed_databases_port_check CHECK (port BETWEEN 1 AND 65535),
    CONSTRAINT managed_databases_connection_options_check
        CHECK (connection_options IS NULL OR jsonb_typeof(connection_options) = 'object')
);

CREATE TABLE public.group_database_permissions (
    group_id        BIGINT NOT NULL REFERENCES public.access_groups(id),
    database_id     BIGINT NOT NULL REFERENCES public.managed_databases(id),
    access_level    VARCHAR(20) NOT NULL,
    granted_by      BIGINT REFERENCES public.users(id),
    granted_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY (group_id, database_id),
    CONSTRAINT group_database_permissions_access_level_check
        CHECK (access_level IN ('view_only', 'view_edit'))
);

CREATE INDEX group_database_permissions_database_id_idx
    ON public.group_database_permissions (database_id);

CREATE TABLE public.sessions (
    id                   UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id              BIGINT NOT NULL REFERENCES public.users(id),
    created_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_seen_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    idle_expires_at      TIMESTAMPTZ NOT NULL,
    absolute_expires_at  TIMESTAMPTZ NOT NULL,
    revoked_at           TIMESTAMPTZ
);

CREATE INDEX sessions_user_id_idx ON public.sessions (user_id);

CREATE TABLE public.session_tokens (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id         UUID NOT NULL REFERENCES public.sessions(id),
    token_hash         BYTEA NOT NULL UNIQUE,
    issued_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    replaced_at        TIMESTAMPTZ,
    grace_expires_at   TIMESTAMPTZ
);

CREATE INDEX session_tokens_session_id_idx ON public.session_tokens (session_id);

-- A session has at most one current token; replaced tokens can retain a grace period.
CREATE UNIQUE INDEX session_tokens_current_per_session_key
    ON public.session_tokens (session_id)
    WHERE replaced_at IS NULL;

CREATE TABLE public.migration_drafts (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    database_id    BIGINT NOT NULL REFERENCES public.managed_databases(id),
    created_by     BIGINT NOT NULL REFERENCES public.users(id),
    title          VARCHAR(255) NOT NULL,
    input_mode     VARCHAR(10) NOT NULL,
    operations     JSONB,
    sql_text       TEXT,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT migration_drafts_input_mode_check
        CHECK (input_mode IN ('visual', 'sql')),
    CONSTRAINT migration_drafts_operations_check
        CHECK (operations IS NULL OR jsonb_typeof(operations) = 'array')
);

CREATE INDEX migration_drafts_database_id_idx ON public.migration_drafts (database_id);

CREATE TABLE public.migration_executions (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    database_id         BIGINT NOT NULL REFERENCES public.managed_databases(id),
    draft_id            BIGINT REFERENCES public.migration_drafts(id),
    executed_by         BIGINT NOT NULL REFERENCES public.users(id),
    description         TEXT,
    sql_text            TEXT NOT NULL,
    attempted_version   BIGINT NOT NULL,
    applied_version     BIGINT,
    status              VARCHAR(12) NOT NULL,
    error_message       TEXT,
    started_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at         TIMESTAMPTZ,

    CONSTRAINT migration_executions_status_check
        CHECK (status IN ('running', 'succeeded', 'failed')),
    CONSTRAINT migration_executions_attempted_version_check
        CHECK (attempted_version > 0),
    CONSTRAINT migration_executions_applied_version_check
        CHECK (applied_version IS NULL OR applied_version > 0),
    CONSTRAINT migration_executions_success_version_check
        CHECK (
            (status = 'succeeded' AND applied_version IS NOT NULL)
            OR (status IN ('running', 'failed') AND applied_version IS NULL)
        )
);

-- Failed/running attempts can repeat a version; a successful version cannot.
CREATE UNIQUE INDEX migration_executions_applied_version_key
    ON public.migration_executions (database_id, applied_version)
    WHERE status = 'succeeded';

CREATE INDEX migration_executions_database_started_at_idx
    ON public.migration_executions (database_id, started_at DESC);
CREATE INDEX migration_executions_draft_id_idx ON public.migration_executions (draft_id);

COMMENT ON COLUMN public.users.password_hash IS
    'Application-provided password hash; never a plaintext password.';
COMMENT ON COLUMN public.users.is_platform_admin IS
    'Platform administration role; does not itself grant managed-database access.';
COMMENT ON COLUMN public.managed_databases.encrypted_password IS
    'Encrypted target-database credential; keep its encryption key outside this database.';
COMMENT ON COLUMN public.session_tokens.token_hash IS
    'Hash of an opaque session token; raw cookie tokens are not stored.';
COMMENT ON COLUMN public.migration_executions.applied_version IS
    'Only populated for a succeeded execution; unique per managed database.';

COMMIT;
