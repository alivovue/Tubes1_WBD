func quote(dbms string, parts ...string) (string, error) {
	limit := 63
	delimiter := "\""
	if dbms == "mariadb" {
		limit = 64
		delimiter = "`"
	}
	result := make([]string, len(parts))
	if len(parts) == 0 {
		return "", ErrInvalid
	}
	for i, part := range parts {
		if !adapters.ValidIdentifier(part, limit) {
			return "", ErrInvalid
		}
		if strings.HasPrefix(strings.ToLower(part), "_schakker") {
			return "", ErrInvalid
		}
		result[i] = delimiter + strings.ReplaceAll(part, delimiter, delimiter+delimiter) + delimiter
	}
	return strings.Join(result, "."), nil
}
func expression(dbms, value string) error {
	statements, err := adapters.ParseSQL("SELECT "+value, dbms)
	if err != nil || len(statements) != 1 || statements[0].HasComments {
		return ErrInvalid
	}
	depth := 0
	for i, t := range statements[0].Tokens {
		if i == 0 || t.Literal || t.Quoted {
			continue
		}
		switch strings.ToUpper(t.Value) {
		case "SELECT", "FROM", "INSERT", "UPDATE", "DELETE", "DROP", "ALTER", "CREATE", "COMMIT", "ROLLBACK", ";", "?":
			return ErrInvalid
		case "(":
			depth++
		case ")":
			depth--
			if depth < 0 {
				return ErrInvalid
			}
		}
	}
	if depth != 0 {
		return ErrInvalid
	}
	return nil
}
func dataType(dbms, value string) error {
	if strings.TrimSpace(value) == "" || len(value) > 1000 {
		return ErrInvalid
	}
	if err := expression(dbms, value); err != nil {
		return err
	}
	tokens, err := adapters.ParseSQL("SELECT "+value, dbms)
	if err != nil {
		return err
	}
	for i, t := range tokens[0].Tokens {
		if i == 0 || t.Literal || t.Quoted {
			continue
		}
		switch strings.ToUpper(t.Value) {
		case "DEFAULT", "NOT", "NULL", "PRIMARY", "UNIQUE", "CHECK", "REFERENCES", "GENERATED", "COMMENT", "CONSTRAINT", "AS", "VALUES", "WHERE":
			return ErrInvalid
		}
	}
	return nil
}
func columnSQL(dbms string, c adapters.Column) (string, error) {
	name, err := quote(dbms, c.Name)
	if err != nil {
		return "", err
	}
	if err := dataType(dbms, c.DataType); err != nil {
		return "", err
	}
	typeName := c.DataType
	defaultValue := c.Default
	if dbms == "postgresql" && c.Identity == "" && defaultValue != nil && strings.HasPrefix(*defaultValue, "nextval(") {
		switch strings.ToLower(typeName) {
		case "smallint":
			typeName = "smallserial"
			defaultValue = nil
		case "integer":
			typeName = "serial"
			defaultValue = nil
		case "bigint":
			typeName = "bigserial"
			defaultValue = nil
		}
	}
	result := name + " " + typeName
	if c.Generated != "" {
		if c.GeneratedExpression == nil {
			return "", ErrInvalid
		}
		if err := expression(dbms, *c.GeneratedExpression); err != nil {
			return "", err
		}
		mode := strings.ToUpper(c.Generated)
		if mode == "S" {
			mode = "STORED"
		}
		if mode != "STORED" && mode != "VIRTUAL" {
			return "", ErrInvalid
		}
		if dbms == "postgresql" && mode != "STORED" {
			return "", ErrUnsupported
		}
		result += " GENERATED ALWAYS AS (" + *c.GeneratedExpression + ") " + mode
	} else if c.Identity != "" {
		if dbms == "mariadb" {
			if c.Identity != "auto_increment" {
				return "", ErrInvalid
			}
			result += " AUTO_INCREMENT"
		} else {
			switch c.Identity {
			case "a", "always":
				result += " GENERATED ALWAYS AS IDENTITY"
			case "d", "by_default":
				result += " GENERATED BY DEFAULT AS IDENTITY"
			default:
				return "", ErrInvalid
			}
		}
	} else if defaultValue != nil {
		if err := expression(dbms, *defaultValue); err != nil {
			return "", err
		}
		result += " DEFAULT " + *defaultValue
	}
	if !c.Nullable {
		result += " NOT NULL"
	}
	return result, nil
}
func constraintSQL(dbms string, c adapters.Constraint) (string, error) {
	name, err := quote(dbms, c.Name)
	if err != nil {
		return "", err
	}
	columns := make([]string, len(c.Columns))
	for i, col := range c.Columns {
		columns[i], err = quote(dbms, col)
		if err != nil {
			return "", err
		}
	}
	if (c.Type == "p" || c.Type == "u" || c.Type == "f") && len(columns) == 0 {
		return "", ErrInvalid
	}
	prefix := "CONSTRAINT " + name + " "
	switch c.Type {
	case "p":
		return prefix + "PRIMARY KEY (" + strings.Join(columns, ",") + ")", nil
	case "u":
		return prefix + "UNIQUE (" + strings.Join(columns, ",") + ")", nil
	case "c":
		value := c.Expression
		if value == "" {
			value = strings.TrimSpace(c.Definition)
			if strings.HasPrefix(strings.ToUpper(value), "CHECK ") {
				value = strings.TrimSpace(value[6:])
			}
		}
		if err := expression(dbms, value); err != nil {
			return "", err
		}
		return prefix + "CHECK (" + value + ")", nil
	case "f":
		if c.ReferencedSchema == nil || c.ReferencedTable == nil || len(columns) == 0 || len(c.ReferencedColumns) != len(columns) {
			return "", ErrInvalid
		}
		table, err := quote(dbms, *c.ReferencedSchema, *c.ReferencedTable)
		if err != nil {
			return "", err
		}
		reference := make([]string, len(c.ReferencedColumns))
		for i, column := range c.ReferencedColumns {
			reference[i], err = quote(dbms, column)
			if err != nil {
				return "", err
			}
		}
		result := prefix + "FOREIGN KEY (" + strings.Join(columns, ",") + ") REFERENCES " + table + " (" + strings.Join(reference, ",") + ")"
		for _, rule := range []struct{ name, value string }{{"UPDATE", c.UpdateRule}, {"DELETE", c.DeleteRule}} {
			value := strings.ToUpper(rule.value)
			if value == "" {
				value = "NO ACTION"
			}
			switch value {
			case "NO ACTION", "RESTRICT", "CASCADE", "SET NULL", "SET DEFAULT":
			default:
				return "", ErrInvalid
			}
			result += " ON " + rule.name + " " + value
		}
		return result, nil
	}
	return "", ErrUnsupported
}
func dropConstraint(dbms, table string, c adapters.Constraint) (string, error) {
	name, err := quote(dbms, c.Name)
	if err != nil {
		return "", err
	}
	if dbms == "mariadb" {
		switch c.Type {
		case "p":
			return "ALTER TABLE " + table + " DROP PRIMARY KEY", nil
		case "u":
			return "ALTER TABLE " + table + " DROP INDEX " + name, nil
		case "f":
			return "ALTER TABLE " + table + " DROP FOREIGN KEY " + name, nil
		case "c":
			return "ALTER TABLE " + table + " DROP CONSTRAINT " + name, nil
		}
	}
	return "ALTER TABLE " + table + " DROP CONSTRAINT " + name, nil
}
func indexSQL(dbms, schema, table string, index adapters.Index) (string, error) {
	name, err := quote(dbms, index.Name)
	if err != nil {
		return "", err
	}
	target, err := quote(dbms, schema, table)
	if err != nil {
		return "", err
	}
	if len(index.Columns) == 0 {
		return "", ErrInvalid
	}
	columns := make([]string, 0, len(index.Columns))
	for _, key := range index.Columns {
		if key.PrefixLength < 0 || key.Name != "" && key.Expression != "" {
			return "", ErrInvalid
		}
		var value string
		if key.Expression != "" {
			if dbms == "mariadb" {
				return "", ErrUnsupported
			}
			if err := expression(dbms, key.Expression); err != nil {
				return "", err
			}
			value = key.Expression
		} else {
			value, err = quote(dbms, key.Name)
			if err != nil {
				return "", err
			}
		}
		if key.PrefixLength > 0 {
			if dbms != "mariadb" {
				return "", ErrUnsupported
			}
			value += "(" + strconv.Itoa(key.PrefixLength) + ")"
		}
		if key.Descending {
			value += " DESC"
		}
		columns = append(columns, value)
	}
	method := strings.ToLower(index.Method)
	if method == "" {
		method = "btree"
	}
	prefix := "CREATE "
	if index.Unique {
		prefix += "UNIQUE "
	}
	if dbms == "mariadb" {
		switch method {
		case "btree", "hash":
		case "fulltext":
			prefix += "FULLTEXT "
		case "rtree", "spatial":
			prefix += "SPATIAL "
		default:
			return "", ErrUnsupported
		}
		if len(index.Include) > 0 || index.Predicate != "" {
			return "", ErrUnsupported
		}
		using := ""
		if method == "btree" || method == "hash" {
			using = " USING " + strings.ToUpper(method)
		}
		return prefix + "INDEX " + name + using + " ON " + target + " (" + strings.Join(columns, ",") + ")", nil
	}
	switch method {
	case "btree", "hash", "gin", "gist", "spgist", "brin":
	default:
		return "", ErrUnsupported
	}
	result := prefix + "INDEX " + name + " ON " + target + " USING " + method + " (" + strings.Join(columns, ",") + ")"
	if len(index.Include) > 0 {
		include := make([]string, len(index.Include))
		for i, col := range index.Include {
			include[i], err = quote(dbms, col)
			if err != nil {
				return "", err
			}
		}
		result += " INCLUDE (" + strings.Join(include, ",") + ")"
	}
	if index.Predicate != "" {
		if err := expression(dbms, index.Predicate); err != nil {
			return "", err
		}
		result += " WHERE " + index.Predicate
	}
	return result, nil
}
func literal(dbms string, value any) (string, error) {
	switch v := value.(type) {
	case nil:
		return "NULL", nil
	case string:
		if !utf8.ValidString(v) || strings.ContainsRune(v, 0) {
			return "", ErrInvalid
		}
		return "'" + strings.ReplaceAll(v, "'", "''") + "'", nil
	case bool:
		if v {
			return "TRUE", nil
		}
		return "FALSE", nil
	case []byte:
		if dbms == "mariadb" {
			return "X'" + hex.EncodeToString(v) + "'", nil
		}
		return "decode('" + hex.EncodeToString(v) + "','hex')", nil
	case time.Time:
		if dbms == "postgresql" {
			return literal(dbms, v.UTC().Format(time.RFC3339Nano))
		}
		return literal(dbms, v.UTC().Format("2006-01-02 15:04:05.999999"))
	case json.Number:
		if number, err := strconv.ParseFloat(string(v), 64); err != nil || math.IsInf(number, 0) || math.IsNaN(number) {
			return "", ErrInvalid
		}
		return string(v), nil
	case int:
		return strconv.Itoa(v), nil
	case int64:
		return strconv.FormatInt(v, 10), nil
	case int8:
		return strconv.FormatInt(int64(v), 10), nil
	case int16:
		return strconv.FormatInt(int64(v), 10), nil
	case int32:
		return strconv.FormatInt(int64(v), 10), nil
	case uint:
		return strconv.FormatUint(uint64(v), 10), nil
	case uint8:
		return strconv.FormatUint(uint64(v), 10), nil
	case uint16:
		return strconv.FormatUint(uint64(v), 10), nil
	case uint32:
		return strconv.FormatUint(uint64(v), 10), nil
	case uint64:
		return strconv.FormatUint(v, 10), nil
	case float64:
		if math.IsInf(v, 0) || math.IsNaN(v) {
			return "", ErrInvalid
		}
		return strconv.FormatFloat(v, 'g', -1, 64), nil
	case float32:
		return literal(dbms, float64(v))
	default:
		return "", ErrInvalid
	}
}
