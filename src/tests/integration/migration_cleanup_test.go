func TestDeletingExecutedDraftPreservesSuccessfulAndFailedHistory(t *testing.T) {
	f := newFixture(t, true)
	target := f.register(t)
	f.grant(t, f.editor, target.ID, access.ViewEdit)
	draft, err := f.migrations.SaveDraft(f.ctx, f.editor, target.ID, migration.DraftInput{Title: "Reusable draft", SQL: "SELECT 1"})
	must(t, err)
	review, err := f.migrations.Analyze(f.ctx, f.editor, target.ID, draft.SQL)
	must(t, err)
	success, err := f.migrations.Execute(f.ctx, f.editor, target.ID, migration.ExecuteInput{Review: review, DraftID: draft.ID})
	must(t, err)
	draft, err = f.migrations.SaveDraft(f.ctx, f.editor, target.ID, migration.DraftInput{ID: draft.ID, Title: draft.Title, SQL: "SELECT 1/0", ExpectedUpdatedAt: draft.UpdatedAt})
	must(t, err)
	review, err = f.migrations.Analyze(f.ctx, f.editor, target.ID, draft.SQL)
	must(t, err)
	failed, err := f.migrations.Execute(f.ctx, f.editor, target.ID, migration.ExecuteInput{Review: review, DraftID: draft.ID})
	wantError(t, err, migration.ErrExecution)
	before := make([]dao.MigrationExecution, 0, 2)
	for _, id := range []int64{success.ID, failed.ID} {
		entry, err := f.migrations.Detail(f.ctx, f.editor, target.ID, id)
		must(t, err)
		before = append(before, entry)
	}
	other, err := f.migrations.SaveDraft(f.ctx, f.editor, target.ID, migration.DraftInput{Title: "Keep this draft", SQL: "SELECT 2"})
	must(t, err)
	reader := f.user(t, "draft.reader")
	f.grant(t, reader.ID, target.ID, access.ViewOnly)
	wantError(t, f.migrations.DeleteDraft(f.ctx, reader.ID, target.ID, draft.ID), access.ErrForbidden)
	must(t, f.migrations.DeleteDraft(f.ctx, f.editor, target.ID, draft.ID))
	_, err = f.migrations.Draft(f.ctx, f.editor, target.ID, draft.ID)
	wantError(t, err, access.ErrNotFound)
	_, err = f.migrations.Draft(f.ctx, f.editor, target.ID, other.ID)
	must(t, err)
	for _, expected := range before {
		entry, err := f.migrations.Detail(f.ctx, reader.ID, target.ID, expected.ID)
		must(t, err)
		expected.DraftID = nil
		if !reflect.DeepEqual(entry, expected) {
			t.Fatalf("deleting the draft changed execution history: got %#v, want %#v", entry, expected)
		}
	}
	version, err := f.runtimeStore.MigrationVersion(f.ctx, target.ID)
	must(t, err)
	if version != 1 {
		t.Fatal("deleting the draft changed the migration version")
	}
}

func TestVisualDropColumnsAppliesLocalDependencyCleanup(t *testing.T) {
	f := newFixture(t, true)
	target := f.register(t)
	f.grant(t, f.editor, target.ID, access.ViewEdit)
	_, err := f.dbs.Managed.ExecContext(f.ctx, `CREATE TABLE public.cleanup_columns(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,label TEXT UNIQUE CHECK(length(label)>0),score INTEGER);
CREATE INDEX cleanup_label_idx ON public.cleanup_columns(label);
CREATE INDEX cleanup_expression_idx ON public.cleanup_columns(lower(label));
CREATE INDEX cleanup_partial_idx ON public.cleanup_columns(score) WHERE label IS NOT NULL;
CREATE INDEX cleanup_include_idx ON public.cleanup_columns(score) INCLUDE(label);
INSERT INTO public.cleanup_columns(label,score) VALUES('Kept score',7)`)
	must(t, err)
	operations := []diff.Operation{
		{Kind: "drop_column", Schema: "public", Table: "cleanup_columns", Column: adapters.Column{Name: "label"}},
		{Kind: "drop_column", Schema: "public", Table: "cleanup_columns", Column: adapters.Column{Name: "id"}},
	}
	review, err := f.migrations.AnalyzeChanges(f.ctx, f.editor, target.ID, operations)
	must(t, err)
	if !review.SchemaDiffAvailable || !strings.Contains(review.SQL, "DROP INDEX") || !strings.Contains(review.SQL, "DROP CONSTRAINT") || strings.Contains(review.SQL, "CASCADE") {
		t.Fatalf("review did not expose the local dependency cleanup: %s", review.SQL)
	}
	before, err := f.databases.DescribeTable(f.ctx, f.editor, target.ID, "public", "cleanup_columns")
	must(t, err)
	if len(before.Columns) != 3 {
		t.Fatal("analysis changed the target schema")
	}
	_, err = f.migrations.Execute(f.ctx, f.editor, target.ID, migration.ExecuteInput{Review: review})
	must(t, err)
	after, err := f.databases.DescribeTable(f.ctx, f.editor, target.ID, "public", "cleanup_columns")
	must(t, err)
	if len(after.Columns) != 1 || after.Columns[0].Name != "score" || len(after.Constraints) != 0 || len(after.Indexes) != 0 {
		t.Fatalf("column cleanup did not match the reviewed schema: %#v", after)
	}
	rows, err := f.databases.TableData(f.ctx, f.editor, target.ID, "public", "cleanup_columns", dbmanagement.PageOptions{Limit: 10})
	must(t, err)
	if len(rows.Rows) != 1 || fmt.Sprint(rows.Rows[0][0]) != "7" {
		t.Fatal("dropping columns changed the remaining row data")
	}
}

func TestVisualDropForeignKeyDependencyShowsClearHTTPError(t *testing.T) {
	f := newFixture(t, true)
	target := f.register(t)
	f.grant(t, f.editor, target.ID, access.ViewEdit)
	_, err := f.dbs.Managed.ExecContext(f.ctx, `CREATE TABLE public.cleanup_parents(id INTEGER PRIMARY KEY,label TEXT);
CREATE TABLE public.cleanup_children(id INTEGER PRIMARY KEY,parent_id INTEGER,CONSTRAINT cleanup_children_parent_fk FOREIGN KEY(parent_id) REFERENCES public.cleanup_parents(id))`)
	must(t, err)
	operations := []diff.Operation{{Kind: "drop_column", Schema: "public", Table: "cleanup_parents", Column: adapters.Column{Name: "id"}}}
	_, err = f.migrations.AnalyzeChanges(f.ctx, f.editor, target.ID, operations)
	wantError(t, err, diff.ErrDependency)
	identity, raw := f.login(t, "it.editor")
	csrf, err := f.access.CSRFToken(identity)
	must(t, err)
	encoded, err := json.Marshal(operations)
	must(t, err)
	form := url.Values{"csrf": {csrf}, "action": {"analyze_visual"}, "db": {fmt.Sprint(target.ID)}, "description": {"Drop referenced column"}, "operations": {string(encoded)}}
	handler := userHandler(t, f)
	response := apiRequest(t, handler, http.MethodPost, "/migrations/new", raw, form)
	if response.Code != http.StatusConflict || !strings.Contains(response.Body.String(), "cleanup_children_parent_fk") || !strings.Contains(response.Body.String(), "CASCADE") {
		t.Fatalf("dependency error was not rendered with its blocker and CASCADE guidance: %d", response.Code)
	}
	history, err := f.migrations.History(f.ctx, f.editor, target.ID, 50, 0)
	must(t, err)
	if len(history) != 0 {
		t.Fatal("a blocked visual change created execution history")
	}
}

func TestViewDependencyFailureExplainsCascadeAndRollsBack(t *testing.T) {
	f := newFixture(t, true)
	target := f.register(t)
	f.grant(t, f.editor, target.ID, access.ViewEdit)
	_, err := f.dbs.Managed.ExecContext(f.ctx, `CREATE TABLE public.cleanup_view_source(id INTEGER PRIMARY KEY,payload TEXT);
CREATE VIEW public.cleanup_dependent_view AS SELECT payload FROM public.cleanup_view_source`)
	must(t, err)
	review, err := f.migrations.AnalyzeChanges(f.ctx, f.editor, target.ID, []diff.Operation{{Kind: "drop_column", Schema: "public", Table: "cleanup_view_source", Column: adapters.Column{Name: "payload"}}})
	must(t, err)
	execution, err := f.migrations.Execute(f.ctx, f.editor, target.ID, migration.ExecuteInput{Review: review})
	wantError(t, err, migration.ErrExecution)
	if !strings.Contains(execution.ErrorMessage, "CASCADE") || !strings.Contains(execution.ErrorMessage, "rolled back") {
		t.Fatalf("view dependency failure has no clear remedy: %s", execution.ErrorMessage)
	}
	detail, err := f.databases.DescribeTable(f.ctx, f.editor, target.ID, "public", "cleanup_view_source")
	must(t, err)
	if len(detail.Columns) != 2 || !f.tableExists(t, "cleanup_dependent_view") {
		t.Fatal("dependency failure changed the table or its dependent view")
	}
}
