BEGIN;
SET LOCAL search_path=pg_catalog,public;
CREATE TABLE public.admin_users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username VARCHAR(100) NOT NULL,
 display_name VARCHAR(150) NOT NULL,
 password_hash TEXT NOT NULL,
 is_active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 -- Provenance makes the two-database migration rerunnable without ID guessing.
 legacy_source_id UUID,
 legacy_user_id BIGINT,
 migration_pending BOOLEAN NOT NULL DEFAULT FALSE,
 CONSTRAINT admin_users_legacy_source_unique UNIQUE(legacy_source_id,legacy_user_id),
 CONSTRAINT admin_users_legacy_source_pair CHECK ((legacy_source_id IS NULL)=(legacy_user_id IS NULL))
);
CREATE UNIQUE INDEX admin_users_username_lower_key ON public.admin_users(lower(username));
CREATE TABLE public.admin_sessions (
 id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
 admin_id BIGINT NOT NULL REFERENCES public.admin_users(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 last_seen_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 idle_expires_at TIMESTAMPTZ NOT NULL,
 absolute_expires_at TIMESTAMPTZ NOT NULL,
 revoked_at TIMESTAMPTZ
);
CREATE INDEX admin_sessions_admin_id_idx ON public.admin_sessions(admin_id);
CREATE TABLE public.admin_session_tokens (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 session_id UUID NOT NULL REFERENCES public.admin_sessions(id),
 token_hash BYTEA NOT NULL UNIQUE,
 issued_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 replaced_at TIMESTAMPTZ,
 grace_expires_at TIMESTAMPTZ
);
CREATE INDEX admin_session_tokens_session_id_idx ON public.admin_session_tokens(session_id);
CREATE UNIQUE INDEX admin_session_tokens_current_per_session_key ON public.admin_session_tokens(session_id) WHERE replaced_at IS NULL;
COMMIT;
